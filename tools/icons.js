// Copies the Lucide icons the app uses into src/icons.js, so they work offline and under the app's
// content-security policy. To add one: put its name below (see lucide.dev) and run npm run lucide.
import { readFile, writeFile } from 'node:fs/promises';

const NAMES = [
  'calendar-check', 'folder-kanban', 'mail', 'chevron-left', 'chevron-right', 'ellipsis', 'settings',
  'calendar', 'calendar-range', 'calendar-plus', 'list', 'kanban', 'plus', 'folder-plus', 'import', 'square-check-big',
  'refresh-cw', 'link', 'video', 'trash-2', 'copy', 'send', 'file-spreadsheet', 'pencil', 'sparkles', 'palette'
];
const pkg = new URL('../node_modules/lucide-static/', import.meta.url);
const { version } = JSON.parse(await readFile(new URL('package.json', pkg), 'utf8'));
const licence = (await readFile(new URL('LICENSE', pkg), 'utf8')).trim();
const icons = {};
for (const name of NAMES) {
  const svg = await readFile(new URL(`icons/${name}.svg`, pkg), 'utf8');
  icons[name] = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*class="[^"]*"/, ` class="i i-${name}" aria-hidden="true" focusable="false"`)
    .replace(/\s*(width|height)="24"/g, '')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .replace(/ \/>/g, '/>')
    .trim();
}
const out = `// Generated by tools/icons.js from lucide-static ${version}. Don't edit by hand: npm run lucide.
/*
${licence}
*/
(function (root) {
  root.Icons = ${JSON.stringify(icons, null, 2)};
})(typeof window !== 'undefined' ? window : globalThis);
`;
await writeFile(new URL('../src/icons.js', import.meta.url), out);
console.log(`src/icons.js: ${NAMES.length} icons from lucide-static ${version}`);
